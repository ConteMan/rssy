func (p *Parser) checkItemCount(feed *gofeed.Feed) ValidationCheck {
	count := len(feed.Items)
	if count == 0 {
		return ValidationCheck{
			Name:     "Item Count",
			Passed:   false,
			Message:  "Feed contains no items",
			Severity: "warning",
		}
	}
	return ValidationCheck{
		Name:     "Item Count",
		Passed:   true,
		Message:  formatItemCount(count),
		Severity: "warning",
	}
}

func formatItemCount(count int) string {
	if count == 1 {
		return "Feed contains 1 item"
	}
	return fmt.Sprintf("Feed contains %d items", count)
}

func (p *Parser) checkItemTitles(feed *gofeed.Feed) ValidationCheck {
	missing := 0
	for _, item := range feed.Items {
		if item.Title == "" {
			missing++
		}
	}
	if missing > 0 {
		return ValidationCheck{
			Name:     "Item Titles",
			Passed:   false,
			Message:  fmt.Sprintf("%d item(s) missing title", missing),
			Severity: "error",
		}
	}
	return ValidationCheck{
		Name:     "Item Titles",
		Passed:   true,
		Message:  "All items have titles",
		Severity: "error",
	}
}

func (p *Parser) checkItemLinks(feed *gofeed.Feed) ValidationCheck {
	missing := 0
	invalid := 0
	for _, item := range feed.Items {
		if item.Link == "" {
			missing++
		} else if _, err := url.ParseRequestURI(item.Link); err != nil {
			invalid++
		}
	}
	if missing > 0 || invalid > 0 {
		msg := ""
		if missing > 0 {
			msg = fmt.Sprintf("%d item(s) missing link", missing)
		}
		if invalid > 0 {
			if msg != "" {
				msg += ", "
			}
			msg += fmt.Sprintf("%d item(s) have invalid links", invalid)
		}
		return ValidationCheck{
			Name:     "Item Links",
			Passed:   false,
			Message:  msg,
			Severity: "warning",
		}
	}
	return ValidationCheck{
		Name:     "Item Links",
		Passed:   true,
		Message:  "All items have valid links",
		Severity: "warning",
	}
}

func (p *Parser) checkItemDates(feed *gofeed.Feed) ValidationCheck {
	missing := 0
	future := 0
	now := time.Now()

	for _, item := range feed.Items {
		if item.PublishedParsed == nil && item.UpdatedParsed == nil {
			missing++
		} else {
			pubDate := item.PublishedParsed
			if pubDate == nil {
				pubDate = item.UpdatedParsed
			}
			if pubDate != nil && pubDate.After(now.Add(24*time.Hour)) {
				future++
			}
		}
	}

	if missing > 0 || future > 0 {
		msg := ""
		if missing > 0 {
			msg = fmt.Sprintf("%d item(s) missing date", missing)
		}
		if future > 0 {
			if msg != "" {
				msg += ", "
			}
			msg += fmt.Sprintf("%d item(s) have future dates", future)
		}
		return ValidationCheck{
			Name:     "Item Dates",
			Passed:   false,
			Message:  msg,
			Severity: "warning",
		}
	}
	return ValidationCheck{
		Name:     "Item Dates",
		Passed:   true,
		Message:  "All items have valid dates",
		Severity: "warning",
	}
}

func (p *Parser) checkItemGUIDs(feed *gofeed.Feed) ValidationCheck {
	missing := 0
	duplicates := make(map[string]int)

	for _, item := range feed.Items {
		if item.GUID == "" {
			missing++
		} else {
			duplicates[item.GUID]++
		}
	}

	dupCount := 0
	for _, count := range duplicates {
		if count > 1 {
			dupCount++
		}
	}

	if missing > 0 || dupCount > 0 {
		msg := ""
		if missing > 0 {
			msg = fmt.Sprintf("%d item(s) missing GUID", missing)
		}
		if dupCount > 0 {
			if msg != "" {
				msg += ", "
			}
			msg += fmt.Sprintf("%d duplicate GUID(s) found", dupCount)
		}
		return ValidationCheck{
			Name:     "Item GUIDs",
			Passed:   false,
			Message:  msg,
			Severity: "warning",
		}
	}
	return ValidationCheck{
		Name:     "Item GUIDs",
		Passed:   true,
		Message:  "All items have unique GUIDs",
		Severity: "warning",
	}
}

func (p *Parser) checkItemDescriptions(feed *gofeed.Feed) ValidationCheck {
	missing := 0
	for _, item := range feed.Items {
		if item.Description == "" && item.Content == "" {
			missing++
		}
	}
	if missing > 0 {
		return ValidationCheck{
			Name:     "Item Content",
			Passed:   false,
			Message:  fmt.Sprintf("%d item(s) missing description/content", missing),
			Severity: "info",
		}
	}
	return ValidationCheck{
		Name:     "Item Content",
		Passed:   true,
		Message:  "All items have content",
		Severity: "info",
	}
}
