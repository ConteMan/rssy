package parser

import (
	"fmt"
	"net/url"
	"time"

	"github.com/mmcdole/gofeed"
)

func (p *Parser) validate(feed *gofeed.Feed) *ValidationResult {
	result := &ValidationResult{
		Checks: []ValidationCheck{},
	}

	// Channel/Feed level checks
	result.addCheck(p.checkTitle(feed))
	result.addCheck(p.checkLink(feed))
	result.addCheck(p.checkDescription(feed))
	result.addCheck(p.checkLanguage(feed))
	result.addCheck(p.checkLastBuildDate(feed))
	result.addCheck(p.checkGenerator(feed))
	result.addCheck(p.checkImage(feed))

	// Item level checks
	result.addCheck(p.checkItemCount(feed))
	result.addCheck(p.checkItemTitles(feed))
	result.addCheck(p.checkItemLinks(feed))
	result.addCheck(p.checkItemDates(feed))
	result.addCheck(p.checkItemGUIDs(feed))
	result.addCheck(p.checkItemDescriptions(feed))

	// Calculate score
	result.calculateScore()

	return result
}

func (v *ValidationResult) addCheck(check ValidationCheck) {
	v.Checks = append(v.Checks, check)
}

func (v *ValidationResult) calculateScore() {
	v.MaxScore = 0
	v.Score = 0

	for _, check := range v.Checks {
		switch check.Severity {
		case "error":
			v.MaxScore += 10
			if check.Passed {
				v.Score += 10
			}
		case "warning":
			v.MaxScore += 5
			if check.Passed {
				v.Score += 5
			}
		case "info":
			v.MaxScore += 2
			if check.Passed {
				v.Score += 2
			}
		}
	}

	v.IsValid = true
	for _, check := range v.Checks {
		if !check.Passed && check.Severity == "error" {
			v.IsValid = false
			break
		}
	}
}

func (p *Parser) checkTitle(feed *gofeed.Feed) ValidationCheck {
	if feed.Title == "" {
		return ValidationCheck{
			Name:     "Feed Title",
			Passed:   false,
			Message:  "Feed is missing a title element",
			Severity: "error",
		}
	}
	return ValidationCheck{
		Name:     "Feed Title",
		Passed:   true,
		Message:  "Feed has a valid title",
		Severity: "error",
	}
}

func (p *Parser) checkLink(feed *gofeed.Feed) ValidationCheck {
	if feed.Link == "" {
		return ValidationCheck{
			Name:     "Feed Link",
			Passed:   false,
			Message:  "Feed is missing a link to the website",
			Severity: "error",
		}
	}
	if _, err := url.ParseRequestURI(feed.Link); err != nil {
		return ValidationCheck{
			Name:     "Feed Link",
			Passed:   false,
			Message:  "Feed link is not a valid URL",
			Severity: "error",
		}
	}
	return ValidationCheck{
		Name:     "Feed Link",
		Passed:   true,
		Message:  "Feed has a valid website link",
		Severity: "error",
	}
}

